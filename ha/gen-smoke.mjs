// ------------------------------------------------------------------ the four probe sensors
// One trigger-based block: every minute it finds the Inkbird's probe sensors, reads them (°F, rounded),
// and each probe sensor keeps its last 20 minutes in an attribute to work out how fast it's rising.
const discover = `{% set ov = states('input_text.smoke_probes') %}
          {% if ov not in ['', 'unknown', 'unavailable'] %}{% set l = ov.split(',') | map('trim') | list %}
          {% else %}
            {% set all = integration_entities('inkbird') | select('match', 'sensor\\\\.') | list %}
            {% set ns = namespace(l=[]) %}
            {% for n in range(1, ${N + 1}) %}{% set ns.l = ns.l + [all | select('search', 'probe_' ~ n ~ '$') | first | default('')] %}{% endfor %}
            {% set l = ns.l %}
          {% endif %}
          {{ (l + ${J(IDX.map(() => ""))})[:${N}] }}`;
const read = `{% set ns = namespace(out=[]) %}
          {% for e in ids %}
            {% set l = expand(e) if e else [] %}{% set s = l[0] if l | count > 0 else none %}
            {% set seen = (s.last_reported if s and s.last_reported is defined else (s.last_updated if s else none)) %}
            {% set ok = s is not none and s.state | is_number and seen is not none and (now() - seen).total_seconds() < 300 %}
            {% set v = s.state | float(0) if ok else 0 %}
            {% if ok and (s.attributes.unit_of_measurement | default('°F')) == '°C' %}{% set v = v * 9 / 5 + 32 %}{% endif %}
            {% set ns.out = ns.out + [(v | round(0) | int) if ok and -40 < v < 1100 else none] %}
          {% endfor %}{{ ns.out }}`;

