// ------------------------------------------------------------------ the watcher
// Every minute, one template works out what's new for each probe and returns
// {"msgs": [...], "flags": [per-probe flag strings], "phones": bool}. Flags remember what's been said
// ("n" near, "d@min" done, "a" got it, "r1"/"r2" reminders, "w@min" holding steady, "s" stall said,
// "f" smoker falling, "o@min" smoker off its setting, "O" said, "l" lost). Minutes are epoch minutes.
const watch = `{% set m = (now().timestamp() / 60) | int %}
          {% set out = namespace(msgs=[], flags=[], phones=false, lost=[], labeled=0, gone=0) %}
          {% for i in range(1, ${N + 1}) %}
            {% set food = states('input_text.smoke_probe_' ~ i ~ '_food') %}{% set food = '' if food in ['unknown', 'unavailable'] else food %}
            {% set what = 'the ' ~ (food | lower) %}
            {% set kind = states('input_select.smoke_probe_' ~ i ~ '_kind') %}
            {% set target = states('input_number.smoke_probe_' ~ i ~ '_target') | float(0) | int %}
            {% set e = 'sensor.smoke_probe_' ~ i %}{% set l = expand(e) %}{% set s = l[0] if l | count > 0 else none %}
            {% set ok = s is not none and s.state | is_number %}
            {% set v = s.state | float(0) | int if ok else 0 %}
            {% set rate = s.attributes.rate if ok and s.attributes.rate is defined else none %}
            {% set f = namespace(d={}) %}
            {% for tok in (states('input_text.smoke_probe_' ~ i ~ '_flags') | replace('unknown', '') | replace('unavailable', '')).split() %}
              {% set kv = tok.split('@') %}{% set f.d = dict(f.d, **{kv[0]: (kv[1] | int(0) if kv | count > 1 else 0)}) %}
            {% endfor %}
            {% set d = namespace(v=f.d) %}
            {% if food %}
              {% set out.labeled = out.labeled + 1 %}
              {% if not ok %}
                {% set away = (now() - s.last_changed).total_seconds() if s is not none else 9999 %}
                {% if away >= 180 %}
                  {% set out.gone = out.gone + 1 %}
                  {% if 'l' not in d.v %}{% set out.lost = out.lost + [[i, what]] %}{% set d.v = dict(d.v, l=0) %}{% endif %}
                {% endif %}
              {% else %}
                {% set d.v = dict(d.v | items | rejectattr(0, 'eq', 'l') | list) %}
                {% if kind == 'food' and target > 0 %}
                  {% if v < target - 15 %}
                    {% set d.v = dict(d.v | items | rejectattr(0, 'in', ['n', 'd', 'a', 'r1', 'r2']) | list) %}
                  {% elif v >= target and 'd' not in d.v %}
                    {% set out.msgs = out.msgs + ['The ' ~ (food | lower) ~ ' hit ' ~ target ~ '. Time to take it off.'] %}{% set out.phones = true %}
                    {% set d.v = dict(d.v, d=m, n=0) %}
                  {% elif v >= target - 10 and v < target and 'n' not in d.v and 'd' not in d.v %}
                    {% set out.msgs = out.msgs + ['The ' ~ (food | lower) ~ ' is at ' ~ v ~ ', almost to ' ~ target ~ '.'] %}
                    {% set d.v = dict(d.v, n=0) %}
                  {% elif 'd' in d.v and 'a' not in d.v and v >= target - 5 %}
                    {% for r, after in [['r1', 10], ['r2', 20]] %}
                      {% if r not in d.v and m - d.v['d'] >= after and ('r1' in d.v or r == 'r1') %}
                        {% set out.msgs = out.msgs + ['Reminder: the ' ~ (food | lower) ~ ' is done. It is at ' ~ v ~ '.'] %}{% set out.phones = true %}
                        {% set d.v = dict(d.v, **{r: 0}) %}
                      {% endif %}
                    {% endfor %}
                  {% endif %}
                  {% if target >= 190 and 150 <= v <= 180 and rate is number and -2.5 < rate < 2.5 %}
                    {% if 'w' not in d.v %}{% set d.v = dict(d.v, w=m) %}
                    {% elif m - d.v['w'] >= 30 and 's' not in d.v %}
                      {% set out.msgs = out.msgs + ['The ' ~ (food | lower) ~ ' has been stuck around ' ~ v ~ ' for half an hour. That is the stall, and it is normal for big cuts. Wrap it if you want to push through.'] %}
                      {% set d.v = dict(d.v, s=0) %}
                    {% endif %}
                  {% else %}{% set d.v = dict(d.v | items | rejectattr(0, 'eq', 'w') | list) %}
                  {% endif %}
                {% elif kind == 'smoker' %}
                  {% if rate is number and rate <= -50 and 'f' not in d.v and (target == 0 or v < target - 20) %}
                    {% set out.msgs = out.msgs + ['The smoker is dropping fast. It is at ' ~ v ~ '. Check the pellets and the fire.'] %}{% set out.phones = true %}
                    {% set d.v = dict(d.v, f=0) %}
                  {% elif rate is number and rate > 0 %}{% set d.v = dict(d.v | items | rejectattr(0, 'eq', 'f') | list) %}
                  {% endif %}
                  {% if target > 0 and (v - target) | abs > 25 %}
                    {% if 'o' not in d.v %}{% set d.v = dict(d.v, o=m) %}
                    {% elif m - d.v['o'] >= 10 and 'O' not in d.v %}
                      {% set out.msgs = out.msgs + ['The smoker is at ' ~ v ~ ', and it is set for ' ~ target ~ '.'] %}{% set d.v = dict(d.v, O=0) %}
                    {% endif %}
                  {% elif target > 0 and (v - target) | abs <= 15 %}{% set d.v = dict(d.v | items | rejectattr(0, 'in', ['o', 'O']) | list) %}
                  {% endif %}
                {% endif %}
              {% endif %}
            {% endif %}
            {% set ns2 = namespace(t=[]) %}
            {% for k, val in d.v | dictsort %}{% set ns2.t = ns2.t + [k ~ ('@' ~ val if val else '')] %}{% endfor %}
            {% set out.flags = out.flags + [ns2.t | join(' ')] %}
          {% endfor %}
          {% if out.lost | count and out.gone == out.labeled %}
            {% set out.msgs = out.msgs + ['I lost the Inkbird. It might be off, out of range, or out of battery.'] %}{% set out.phones = true %}
          {% else %}
            {% for p in out.lost %}{% set out.msgs = out.msgs + ['Probe ' ~ p[0] ~ ', ' ~ p[1] ~ ', stopped reading. Check that it is plugged in all the way.'] %}{% endfor %}
          {% endif %}
          {{ {'msgs': out.msgs, 'flags': out.flags, 'phones': out.phones} }}`;

