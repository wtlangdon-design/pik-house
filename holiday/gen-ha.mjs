const t12 = (hm) => { let [h, m] = hm.split(":").map(Number); const ap = h >= 12 ? "PM" : "AM"; h = h % 12 || 12; return `${h}:${String(m).padStart(2, "0")} ${ap}`; };
const clip = (s, n) => (s.length > n ? s.slice(0, n - 1).trimEnd() + "…" : s);
const title = plan.title;

const dishName = Object.fromEntries(plan.dishes.map((d) => [d.id, d.name]));
// s: a few words for group alarms ("Four things at 3:00: stuffing, green beans, …"): the dish, or the job's first clause.
const short = (t) => (t.rid ? (dishName[t.rid] || t.rid) : t.text.split(/[;:.(]/)[0]).trim().toLowerCase().replace(/^burner \d /, "");
const tasks = plan.tasks.map((t) => ({ i: t.id, at: `${plan.days[t.day]} ${t.hm}`, d: SHORT[t.day] || t.day, h: t12(t.hm), x: t.text, s: short(t) }));
// Each recipe's run from start to finish (the same order the kitchen screens walk), for Pik's "next step".
// Jobs that aren't part of a recipe form a "kitchen" run. One entry per recipe step, or one per part without steps.
const DAYS = Object.keys(plan.days);
const steps = {};
plan.tasks.slice().sort((a, b) => DAYS.indexOf(a.day) - DAYS.indexOf(b.day) || (a.hm < b.hm ? -1 : a.hm > b.hm ? 1 : 0)).forEach((t) => {
  const g = t.rid || "kitchen";
  const r = t.rid ? plan.recipes.find((x) => x.id === t.rid) : null;
  steps[g] = steps[g] || { n: dishName[g] || (r ? r.name : "Kitchen"), e: [] };
  const own = (t.steps || []).map(([, i]) => r.steps[i]);
  const partTimer = own.some((st) => st.tm) ? null : t.tm || null;
  const tips = (t.tips || []).map(([q, a]) => q + " " + a).join(" ") || null;
  if (!own.length) { steps[g].e.push({ k: t.id, x: t.text, i: "", tm: t.tm || null, ifs: tips }); return; }
  own.forEach((st) => {
    const ing = (st.ing || []).map(([k, q, w]) => { const gi = k >= 0 ? r.ingr[k] : null; return ((q !== undefined && q !== null ? q : gi ? gi[0] : "") + " " + (w || (gi ? gi[1] : ""))).trim(); }).filter(Boolean);
    steps[g].e.push({ k: t.id, x: st.t, i: ing.join("; "), tm: st.tm || partTimer, m: st.min || null, ifs: tips });
  });
});
