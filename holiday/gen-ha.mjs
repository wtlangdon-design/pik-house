// Builds the Home Assistant package for one holiday plan:
//   node holiday/gen-ha.mjs thanksgiving-2026 tg26
// writes ha/packages/pik_holiday_<plan id>.yaml. The plan JSON is the single source of truth;
// the card bundles the same file. Regenerate after any change to the plan.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const [file = "thanksgiving-2026", P = "tg26"] = process.argv.slice(2);
const plan = JSON.parse(readFileSync(join(here, file + ".json"), "utf8"));
const J = (v) => JSON.stringify(v); // JSON is valid YAML
const SHORT = { tue: "Tue", wed: "Wed", thu: "Thu", fri: "Fri", sat: "Sat", sun: "Sun", mon: "Mon" };
const t12 = (hm) => { let [h, m] = hm.split(":").map(Number); const ap = h >= 12 ? "PM" : "AM"; h = h % 12 || 12; return `${h}:${String(m).padStart(2, "0")} ${ap}`; };
const clip = (s, n) => (s.length > n ? s.slice(0, n - 1).trimEnd() + "…" : s);
const who = (w) => (w === "AB" ? "Both" : "Cook " + w);
const title = plan.title;

const tasks = plan.tasks.map((t) => ({ i: t.id, at: `${plan.days[t.day]} ${t.hm}`, d: SHORT[t.day] || t.day, h: t12(t.hm), w: who(t.who), x: t.text }));
const out = [];
const L = (s = "") => out.push(s);

L(`# ${title}: holiday cooking mode for the plan in holiday/${file}.json.`);
L(`# GENERATED by holiday/gen-ha.mjs. Don't edit by hand; change the plan and regenerate.`);
L(`#`);
L(`# What it adds (prefix "${P}"):`);
L(`#   input_boolean.${P}_<task>      one per planned task and final-hour item: on = ticked off`);
L(`#   input_boolean.${P}_quiet       on = don't read tasks out on the Echos (off by default)`);
L(`#   input_boolean.${P}_push        on = also push each task to both phones (off by default)`);
L(`#   input_number.${P}_turkey_*     latest probe reading for breast, thigh, wing (history = the log)`);
L(`#   automations: read each task out at its time; announce "turkey is done" at 165°F everywhere`);
L(`#   scripts for Pik: holiday_whats_next, holiday_task_done, holiday_log_turkey`);
L(`# Needs pik_kitchen.yaml (timers and script.pik_announce).`);
L();
L(`input_boolean:`);
L(`  ${P}_quiet: { name: ${J(title + ": don't announce tasks on the Echos")}, icon: "mdi:bullhorn-outline" }`);
L(`  ${P}_push: { name: ${J(title + ": also push tasks to phones")}, icon: "mdi:cellphone-message" }`);
for (const t of tasks) L(`  ${P}_${t.i}: { name: ${J(clip(`${title} · ${t.d} ${t.h} · ${t.x}`, 100))}, icon: "mdi:checkbox-marked-circle-outline" }`);
for (const f of plan.finalHour) L(`  ${P}_${f.id}: { name: ${J(clip(`${title} · final hour ${t12(f.hm)} · ${f.text}`, 100))}, icon: "mdi:timer-check-outline" }`);
L();
L(`input_number:`);
for (const s of ["breast", "thigh", "wing"]) L(`  ${P}_turkey_${s}: { name: ${J("Turkey " + s)}, min: 0, max: 250, step: 1, mode: box, unit_of_measurement: "°F", icon: "mdi:thermometer" }`);
L();

// The plan as a compact list, shared by the automation and the scripts.
const planVar = (indent) => `${indent}plan: ${J(tasks)}`;
const turkeyDone = `{{ states('input_number.${P}_turkey_breast') | float(0) >= 165 and states('input_number.${P}_turkey_thigh') | float(0) >= 165 and states('input_number.${P}_turkey_wing') | float(0) >= 165 }}`;

L(`automation:`);
L(`  - id: ${P}_task_alarms`);
L(`    alias: ${J(title + ": read each task out at its time")}`);
L(`    description: "Every minute: any planned task due now and not ticked off is announced on the Echos (and phones, if turned on)."`);
L(`    mode: queued`);
L(`    triggers:`);
L(`      - trigger: time_pattern`);
L(`        minutes: "/1"`);
L(`    conditions:`);
L(`      - "{{ now().strftime('%Y-%m-%d') in [${Object.values(plan.days).map((d) => "'" + d + "'").join(", ")}] }}"`);
L(`    actions:`);
L(`      - variables:`);
L(planVar("          "));
L(`          stamp: "{{ now().strftime('%Y-%m-%d %H:%M') }}"`);
L(`          due: >-`);
L(`            {% set ns = namespace(out=[]) %}`);
L(`            {% for t in plan if t.at == stamp and not is_state('input_boolean.${P}_' ~ t.i, 'on') %}{% set ns.out = ns.out + [t] %}{% endfor %}`);
L(`            {{ ns.out }}`);
L(`      - condition: "{{ due | count > 0 }}"`);
L(`      - event: pik_holiday_task_due`);
L(`        event_data: { plan: ${J(plan.id)}, tasks: "{{ due | map(attribute='i') | list }}" }`);
L(`      - condition: "{{ not is_state('input_boolean.${P}_quiet', 'on') }}"`);
L(`      - action: script.pik_announce`);
L(`        data:`);
L(`          message: >-`);
L(`            {{ due[0].h }}. {% for t in due %}{{ t.w }}: {{ t.x | replace(' → ', ', then ') | replace('→', ', then') | replace('°F', ' degrees') | replace('·', ',') }}{{ ' ' if not loop.last }}{% endfor %}`);
L(`          phones: "{{ is_state('input_boolean.${P}_push', 'on') }}"`);
L();
L(`  - id: ${P}_turkey_done`);
L(`    alias: ${J(title + ": the turkey is done")}`);
L(`    mode: single`);
L(`    triggers:`);
L(`      - trigger: template`);
L(`        value_template: ${J(turkeyDone)}`);
L(`    actions:`);
L(`      - action: script.pik_announce`);
L(`        data:`);
L(`          message: "The turkey is done: 165 degrees in the breast, thigh and wing. Off the smoker, tent it, and rest it 30 to 45 minutes."`);
L(`          phones: true`);
L();

L(`script:`);
L(`  holiday_whats_next:`);
L(`    alias: ${J("Holiday cooking: what's next")}`);
L(`    description: >-`);
L(`      ${title} cooking plan. Returns what's due now, what's next, how many earlier tasks aren't ticked off,`);
L(`      the latest turkey readings, and running kitchen timers. Use for "what's next", "what should I be doing",`);
L(`      "where are we", "how's the turkey". Each task has an id for holiday_task_done.`);
L(`    mode: parallel`);
L(`    sequence:`);
L(`      - variables:`);
L(planVar("          "));
L(`          result: >-`);
L(`            {% set n = now() %}`);
L(`            {% set soon = (n + timedelta(minutes=15)).strftime('%Y-%m-%d %H:%M') %}`);
L(`            {% set back = (n - timedelta(minutes=30)).strftime('%Y-%m-%d %H:%M') %}`);
L(`            {% set ns = namespace(due=[], nxt=[], late=[]) %}`);
L(`            {% for t in plan if not is_state('input_boolean.${P}_' ~ t.i, 'on') %}`);
L(`              {% set row = {'id': t.i, 'when': t.d ~ ' ' ~ t.h, 'who': t.w, 'task': t.x} %}`);
L(`              {% if back <= t.at <= soon %}{% set ns.due = ns.due + [row] %}`);
L(`              {% elif t.at > soon and ns.nxt | count < 5 %}{% set ns.nxt = ns.nxt + [row] %}`);
L(`              {% elif t.at < back %}{% set ns.late = ns.late + [row] %}{% endif %}`);
L(`            {% endfor %}`);
L(`            {% set tk = namespace(r={}) %}`);
L(`            {% for s in ['breast', 'thigh', 'wing'] %}{% set v = states('input_number.${P}_turkey_' ~ s) | float(0) %}{% set tk.r = dict(tk.r, **{s: (v | int if v > 30 else 'no reading')}) %}{% endfor %}`);
L(`            {{ {'now': n.strftime('%a %-I:%M %p'), 'dinner': ${J(plan.subtitle)}, 'due_now': ns.due, 'next': ns.nxt,`);
L(`                'earlier_not_ticked': ns.late[-5:], 'earlier_not_ticked_count': ns.late | count,`);
L(`                'turkey_f': tk.r, 'turkey_done': ${turkeyDone.slice(3, -3)},`);
L(`                'turkey_rule': 'Done only at 165F in the thickest breast, innermost thigh and innermost wing. Never by a timer.'} }}`);
L(`      - stop: "Plan"`);
L(`        response_variable: result`);
L();
L(`  holiday_task_done:`);
L(`    alias: "Holiday cooking: tick a task off"`);
L(`    description: >-`);
L(`      Ticks a task in the ${title} plan off (or back on with done=false). "task" is its id from holiday_whats_next,`);
L(`      or a few words from it ("stuffing in", "potato water"); words pick the unticked task nearest to now.`);
L(`      Use for "the stuffing's in", "done with the brine", "tick off the gravy".`);
L(`    mode: queued`);
L(`    fields:`);
L(`      task: { description: "Task id, or a few words from the task", required: true, selector: { text: null } }`);
L(`      done: { description: "true = ticked off (default), false = not done", default: true, selector: { boolean: null } }`);
L(`    sequence:`);
L(`      - variables:`);
L(planVar("          "));
L(`          want: "{{ done | default(true) | bool }}"`);
L(`          hit: >-`);
L(`            {% set q = task | lower | trim %}`);
L(`            {% set words = q | regex_findall('[a-z0-9]+') %}`);
L(`            {% set ns = namespace(id='', gap=10**9) %}`);
L(`            {% for t in plan %}{% if t.i == q %}{% set ns.id = t.i %}{% set ns.gap = -1 %}{% endif %}{% endfor %}`);
L(`            {% if ns.id == '' %}`);
L(`              {% for t in plan if (is_state('input_boolean.${P}_' ~ t.i, 'on') != want) %}`);
L(`                {% set x = (t.x ~ ' ' ~ t.w) | lower | regex_findall('[a-z0-9]+') %}`);
L(`                {% if words | count > 0 and words | select('in', x) | list | count == words | count %}`);
L(`                  {% set gap = (as_timestamp(t.at) - as_timestamp(now())) | abs %}`);
L(`                  {% if gap < ns.gap %}{% set ns.id = t.i %}{% set ns.gap = gap %}{% endif %}`);
L(`                {% endif %}`);
L(`              {% endfor %}`);
L(`            {% endif %}`);
L(`            {{ ns.id }}`);
L(`      - if: "{{ hit == '' }}"`);
L(`        then:`);
L(`          - variables: { result: { ok: false, message: "No task matches that. Ask holiday_whats_next for the list and use an id." } }`);
L(`          - stop: "No match"`);
L(`            response_variable: result`);
L(`      - action: "input_boolean.turn_{{ 'on' if want else 'off' }}"`);
L(`        target: { entity_id: "input_boolean.${P}_{{ hit }}" }`);
L(`      - variables:`);
L(`          row: "{{ plan | selectattr('i', 'eq', hit) | first }}"`);
L(`          result: { ok: true, id: "{{ hit }}", task: "{{ row.d }} {{ row.h }}: {{ row.x }}", done: "{{ want }}" }`);
L(`      - stop: "Done"`);
L(`        response_variable: result`);
L();
L(`  holiday_log_turkey:`);
L(`    alias: "Holiday cooking: log turkey temperatures"`);
L(`    description: >-`);
L(`      Logs probe readings in °F for the turkey (any of breast, thigh, wing). Returns all three latest readings`);
L(`      and whether it's done. It's done only when all three read 165°F or more. Use for "the breast is 158".`);
L(`    mode: queued`);
L(`    fields:`);
L(`      breast: { description: "Thickest part of the breast, °F", selector: { number: { min: 32, max: 250, mode: box } } }`);
L(`      thigh: { description: "Innermost thigh, °F", selector: { number: { min: 32, max: 250, mode: box } } }`);
L(`      wing: { description: "Innermost wing, °F", selector: { number: { min: 32, max: 250, mode: box } } }`);
L(`    sequence:`);
for (const s of ["breast", "thigh", "wing"]) {
  L(`      - if: "{{ ${s} is defined and ${s} | float(0) > 30 }}"`);
  L(`        then:`);
  L(`          - action: input_number.set_value`);
  L(`            target: { entity_id: input_number.${P}_turkey_${s} }`);
  L(`            data: { value: "{{ ${s} | float | round(0) }}" }`);
}
L(`      - variables:`);
L(`          result: >-`);
L(`            {% set r = namespace(d={}) %}`);
L(`            {% for s in ['breast', 'thigh', 'wing'] %}{% set v = states('input_number.${P}_turkey_' ~ s) | float(0) %}{% set r.d = dict(r.d, **{s: (v | int if v > 30 else 'no reading')}) %}{% endfor %}`);
L(`            {{ {'turkey_f': r.d, 'done': ${turkeyDone.slice(3, -3)}} }}`);
L(`      - stop: "Logged"`);
L(`        response_variable: result`);

const dest = join(here, "..", "ha", "packages", `pik_holiday_${plan.id}.yaml`);
writeFileSync(dest, out.join("\n") + "\n");
console.log("wrote", dest, tasks.length, "tasks,", plan.finalHour.length, "final-hour items");
