  L(`              result: "{{ {'ok': true, 'delays_today': mine, 'message': ('Running behind today: ' ~ (mine | join('; '))) if mine else 'We are on the original schedule.'} }}"`);
  L(`          - stop: "Status"`);
  L(`            response_variable: result`);
  L(`      - if: "{{ act == 'clear' }}"`);
