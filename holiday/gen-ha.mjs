// Builds the Home Assistant package for one holiday plan:
//   node holiday/gen-ha.mjs thanksgiving-2026 tg26
// writes ha/packages/pik_holiday_<plan id>.yaml. The plan JSON is the single source of truth;
// the card bundles the same file. Regenerate after any change to the plan.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const [file = "thanksgiving-2026", P = "tg26"] = process.argv.slice(2);
const plan = JSON.parse(readFileSync(join(here, file + ".json"), "utf8"));
const J = (v) => JSON.stringify(v); // JSON is valid YAML
const SHORT = { tue: "Tue", wed: "Wed", thu: "Thu", fri: "Fri", sat: "Sat", sun: "Sun", mon: "Mon" };
const t12 = (hm) => { let [h, m] = hm.split(":").map(Number); const ap = h >= 12 ? "PM" : "AM"; h = h % 12 || 12; return `${h}:${String(m).padStart(2, "0")} ${ap}`; };
const clip = (s, n) => (s.length > n ? s.slice(0, n - 1).trimEnd() + "…" : s);
const title = plan.title;

const tasks = plan.tasks.map((t) => ({ i: t.id, at: `${plan.days[t.day]} ${t.hm}`, d: SHORT[t.day] || t.day, h: t12(t.hm), x: t.text }));
const dishName = Object.fromEntries(plan.dishes.map((d) => [d.id, d.name]));
// Each recipe's run from start to finish (the same order the kitchen screens walk), for Pik's "next step".
// Jobs that aren't part of a recipe form a "kitchen" run. One entry per recipe step, or one per part without steps.
const DAYS = Object.keys(plan.days);
const steps = {};
plan.tasks.slice().sort((a, b) => DAYS.indexOf(a.day) - DAYS.indexOf(b.day) || (a.hm < b.hm ? -1 : a.hm > b.hm ? 1 : 0)).forEach((t) => {
  const g = t.rid || "kitchen";
  const r = t.rid ? plan.recipes.find((x) => x.id === t.rid) : null;
  steps[g] = steps[g] || { n: dishName[g] || (r ? r.name : "Kitchen"), e: [] };
  const own = (t.steps || []).map(([, i]) => r.steps[i]);
  const partTimer = own.some((st) => st.tm) ? null : t.tm || null;
  if (!own.length) { steps[g].e.push({ k: t.id, x: t.text, i: "", tm: t.tm || null }); return; }
  own.forEach((st) => {
    const ing = (st.ing || []).map(([k, q, w]) => { const gi = k >= 0 ? r.ingr[k] : null; return ((q !== undefined && q !== null ? q : gi ? gi[0] : "") + " " + (w || (gi ? gi[1] : ""))).trim(); }).filter(Boolean);
    steps[g].e.push({ k: t.id, x: st.t, i: ing.join("; "), tm: st.tm || partTimer, m: st.min || null });
  });
});
